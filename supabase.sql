-- City Of Los Santos schema and secure staff review policies.
-- Safe to re-run; does not reset existing data.
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 display_name text not null default 'Community Member',
 role text not null default 'member' check(role in ('member','moderator','admin')),
 created_at timestamptz not null default now()
);
create table if not exists public.forum_posts (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 category text not null check(category in ('announcements','general','gangs','support')),
 title text not null check(char_length(title) between 1 and 120),
 body text not null check(char_length(body) between 1 and 5000),
 created_at timestamptz not null default now()
);
create table if not exists public.applications (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 type text not null, applicant_name text not null, discord_username text not null,
 details text not null, status text not null default 'pending' check(status in ('pending','reviewing','accepted','declined')),
 created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
alter table public.forum_posts enable row level security;
alter table public.applications enable row level security;
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
 insert into public.profiles(id,display_name) values(new.id,coalesce(nullif(split_part(new.email,'@',1),''),'Community Member'));
 return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();
create or replace function public.is_staff()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=(select auth.uid()) and role in ('admin','moderator')); $$;
revoke all on function public.is_staff() from public;
grant execute on function public.is_staff() to authenticated;
drop policy if exists "Profiles are viewable by everyone" on public.profiles;
create policy "Profiles are viewable by everyone" on public.profiles for select using(true);
drop policy if exists "Forum posts are public" on public.forum_posts;
create policy "Forum posts are public" on public.forum_posts for select using(true);
drop policy if exists "Signed-in users can create posts" on public.forum_posts;
create policy "Signed-in users can create posts" on public.forum_posts for insert to authenticated with check(auth.uid()=user_id);
drop policy if exists "Authors can edit own posts" on public.forum_posts;
create policy "Authors can edit own posts" on public.forum_posts for update to authenticated using(auth.uid()=user_id) with check(auth.uid()=user_id);
drop policy if exists "Authors can delete own posts" on public.forum_posts;
create policy "Authors can delete own posts" on public.forum_posts for delete to authenticated using(auth.uid()=user_id);
drop policy if exists "Staff can moderate posts" on public.forum_posts;
create policy "Staff can moderate posts" on public.forum_posts for all to authenticated using(public.is_staff()) with check(public.is_staff());
drop policy if exists "Users can submit applications" on public.applications;
create policy "Users can submit applications" on public.applications for insert to authenticated with check(auth.uid()=user_id);
drop policy if exists "Users can view own applications" on public.applications;
create policy "Users can view own applications" on public.applications for select to authenticated using(auth.uid()=user_id);
drop policy if exists "Staff can review applications" on public.applications;
create policy "Staff can review applications" on public.applications for select to authenticated using(public.is_staff());
drop policy if exists "Staff can update applications" on public.applications;
create policy "Staff can update applications" on public.applications for update to authenticated using(public.is_staff()) with check(public.is_staff());
